"""Generate the geo reference migration from Local Government Directory data.

Source: the daily LGD mirror at https://ramseraph.github.io/opendata/lgd/
(Parquet files of the official lgdirectory.gov.in reports). Download
states, districts and subdistricts listed in data/metadata.json, check their
sha256 against the metadata, then run:

    python -I supabase/scripts/lgd_to_sql.py STATES DISTRICTS SUBDISTRICTS \\
        --states 2,5,9,23 --published-at 2026-11-26 > migration.sql

State codes are LGD codes (2 Himachal Pradesh, 5 Uttarakhand, 9 Uttar
Pradesh, 23 Madhya Pradesh). Requires pyarrow. Adding states later means a new
migration with only the new rows (applied migrations are never edited).
"""

import argparse
import hashlib
import sys

import pyarrow.parquet as pq


def sql_text(value: str) -> str:
    # LGD marks some names with a trailing footnote asterisk ("Jakholi*").
    cleaned = " ".join(value.replace("*", "").split())
    return "'" + cleaned.replace("'", "''") + "'"


def sha256(path: str) -> str:
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("states")
    parser.add_argument("districts")
    parser.add_argument("subdistricts")
    parser.add_argument("--states", dest="state_codes", required=True)
    parser.add_argument("--published-at", required=True)
    args = parser.parse_args()

    wanted = {code.strip() for code in args.state_codes.split(",")}
    states = [r for r in pq.read_table(args.states).to_pylist() if r["state_code"] in wanted]
    districts = [r for r in pq.read_table(args.districts).to_pylist() if r["state_code"] in wanted]
    subdistricts = [
        r for r in pq.read_table(args.subdistricts).to_pylist() if r["state_code"] in wanted
    ]
    district_codes = {r["district_code"] for r in districts}
    if any(r["district_code"] not in district_codes for r in subdistricts):
        sys.exit("a subdistrict refers to a district that is not in the selection")

    out = sys.stdout
    out.write(f"-- LGD reference data: {len(states)} states, {len(districts)} districts, ")
    out.write(f"{len(subdistricts)} subdistricts.\n")
    out.write(f"-- Source: LGD mirror published {args.published_at}; files (sha256):\n")
    for path in (args.states, args.districts, args.subdistricts):
        out.write(f"--   {path.replace(chr(92), '/').rsplit('/', 1)[-1]} {sha256(path)}\n")
    out.write("-- Generated by supabase/scripts/lgd_to_sql.py. Do not edit by hand.\n\n")

    out.write("insert into public.geo_states (code, name) values\n")
    out.write(
        ",\n".join(
            f"  ({int(r['state_code'])}, {sql_text(r['state_name'])})"
            for r in sorted(states, key=lambda r: int(r["state_code"]))
        )
    )
    out.write(";\n\ninsert into public.geo_districts (code, state_code, name) values\n")
    out.write(
        ",\n".join(
            f"  ({int(r['district_code'])}, {int(r['state_code'])}, {sql_text(r['district_name'])})"
            for r in sorted(districts, key=lambda r: int(r["district_code"]))
        )
    )
    out.write(";\n\ninsert into public.geo_subdistricts (code, district_code, name) values\n")
    out.write(
        ",\n".join(
            f"  ({int(r['subdistrict_code'])}, {int(r['district_code'])}, {sql_text(r['subdistrict_name'])})"
            for r in sorted(subdistricts, key=lambda r: int(r["subdistrict_code"]))
        )
    )
    out.write(";\n")


if __name__ == "__main__":
    main()
