-- Global place reference: states, districts and tehsils (sub-districts) from
-- the Local Government Directory (ADR 0023).
--
-- Global lookup tables, not tenant-owned: every organization shares the same
-- official places. Codes are LGD codes. Readable by anyone (the sign-up form
-- needs them, and they are public data); written only by migrations.

create table public.geo_states (
  code integer primary key,
  name text not null check (btrim(name) <> '' and char_length(name) <= 100)
);

create table public.geo_districts (
  code integer primary key,
  state_code integer not null references public.geo_states (code),
  name text not null check (btrim(name) <> '' and char_length(name) <= 100)
);

create table public.geo_subdistricts (
  code integer primary key,
  district_code integer not null references public.geo_districts (code),
  name text not null check (btrim(name) <> '' and char_length(name) <= 100)
);

create index geo_districts_state_idx on public.geo_districts (state_code);
create index geo_subdistricts_district_idx on public.geo_subdistricts (district_code);

alter table public.geo_states enable row level security;
alter table public.geo_districts enable row level security;
alter table public.geo_subdistricts enable row level security;

